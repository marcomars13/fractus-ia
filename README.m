## 🌍 Vision

Fractus est un **moteur fractal universel de détection d’anomalies et de corrélations**, né à la croisée de la physique, de la cryptographie et de l’intelligence artificielle.  
Chaque séquence — image, signal, texte ou ADN — possède une **signature fractale unique**.  
Fractus révèle ces motifs cachés, comme un radar du réel.

